/** `plural(t.home, "tools", 3)` → t.home.tools_other with {n} = 3. */
export function plural<T extends Record<string, unknown>>(group: T, key: string, n: number): string {
  const one = group[`${key}_one`] as string | undefined;
  const other = group[`${key}_other`] as string | undefined;
  return ((n === 1 ? one : other) ?? other ?? one ?? key).replace(/\{n\}/g, String(n));
}
